import { test, expect } from "./backend-fixture";

test("workspace chooser has no inline settings and Settings preserves saved values", async ({ page, backend }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Workspace menu", exact: true }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  const settings = page.getByRole("dialog", { name: "Workspace settings", exact: true });
  await expect(settings.getByLabel("Workspace name")).toHaveValue("Launch team");
  await settings.getByLabel("Workspace name").fill("Changed team");
  await settings.getByRole("button", { name: "Cancel", exact: true }).click();
  expect(backend.snapshot.name).toBe("Launch team");
  await page.getByRole("button", { name: "Workspace menu", exact: true }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await settings.getByLabel("Workspace name").fill("Saved team");
  await settings.getByRole("button", { name: "Save workspace settings" }).click();
  await page.reload();
  await expect(page.getByRole("button", { name: "Switch workspace: Saved team" })).toBeVisible();
  await page.getByRole("button", { name: "Switch workspace: Saved team" }).click();
  await expect(page.getByRole("heading", { name: "Workspaces", exact: true })).toBeVisible();
  await expect(page.getByText("Workspace and team settings", { exact: true })).toHaveCount(0);
  await expect(page.getByLabel("Member name", { exact: true })).toHaveCount(0);
});

test("manual member forms only save deliberately, preserve edits and reject duplicates", async ({ page, backend }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Files & team", exact: true }).click();
  const team = page.getByRole("region", { name: "Team members", exact: true });
  await expect(team.getByRole("listitem")).toHaveCount(2);
  await expect(team.locator("input")).toHaveCount(0);
  const writes = () => backend.requests.filter(p => p.includes("/members/")).length;
  const before = writes();
  await team.getByRole("button", { name: "Add member", exact: true }).click();
  let form = page.getByRole("dialog", { name: "Add member", exact: true });
  await form.getByLabel("Member name").fill("Cancelled person");
  await form.getByRole("button", { name: "Cancel", exact: true }).click();
  expect(writes()).toBe(before);
  await team.getByRole("button", { name: "Add member", exact: true }).click();
  await form.getByRole("button", { name: "Add member", exact: true }).click();
  expect(writes()).toBe(before);
  await form.getByLabel("Member name").fill("Taylor Brooks");
  await form.getByLabel("Email address").fill("taylor@example.com");
  await form.getByLabel("Role", { exact: true }).fill("Producer");
  await form.getByRole("button", { name: "Add member", exact: true }).click();
  await expect(form).toHaveCount(0);
  await expect(team.getByRole("listitem")).toHaveCount(3);
  await team.getByLabel("Actions for Taylor Brooks").click();
  await team.getByRole("button", { name: "Edit member", exact: true }).click();
  form = page.getByRole("dialog", { name: "Edit member", exact: true });
  await form.getByLabel("Member name").fill("Taylor Updated");
  await form.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(team.getByText("Taylor Brooks", { exact: true })).toBeVisible();
  await team.getByLabel("Actions for Taylor Brooks").click();
  await team.getByRole("button", { name: "Edit member", exact: true }).click();
  await form.getByLabel("Member name").fill("Taylor Updated");
  await form.getByLabel("Role", { exact: true }).fill("Lead producer");
  await form.getByRole("button", { name: "Save member", exact: true }).click();
  await expect(form).toHaveCount(0);
  await page.reload();
  await page.getByRole("button", { name: "Files & team", exact: true }).click();
  await expect(team.getByText("Taylor Updated", { exact: true })).toBeVisible();
  await expect(team.getByText("Lead producer", { exact: true })).toBeVisible();
  await team.getByRole("button", { name: "Add member", exact: true }).click();
  form = page.getByRole("dialog", { name: "Add member", exact: true });
  await form.getByLabel("Member name").fill("Another person");
  await form.getByLabel("Email address").fill("TAYLOR@example.com");
  await form.getByLabel("Role", { exact: true }).fill("Editor");
  await form.getByRole("button", { name: "Add member", exact: true }).click();
  await expect(form.getByRole("alert")).toContainText("already exists");
  expect(backend.snapshot.people).toHaveLength(3);
  await form.getByRole("button", { name: "Cancel", exact: true }).click();
  await team.getByRole("button", { name: "Invite account", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Invite member", exact: true })).toBeVisible();
  expect(backend.requests.filter(p => p.endsWith("/invite"))).toHaveLength(0);
});

test("freelancers cannot manage team or workspace settings", async ({ page, backend }) => {
  await page.goto("/"); await backend.worker();
  await page.getByRole("button", { name: "Workspace menu", exact: true }).click();
  await expect(page.getByRole("button", { name: "Settings", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Workspace menu", exact: true }).click();
  await page.getByRole("button", { name: "Files & team", exact: true }).click();
  await expect(page.getByRole("button", { name: "Add member", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Edit member", exact: true })).toHaveCount(0);
});
